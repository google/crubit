"""Resolves an LLVM commit's dev date and outputs it in YYYYmmDD format (UTC).

The dev date of a commit on main is its own; on a release branch it is the
branch's fork from main, since the branch keeps that API.
"""

import datetime
import json
import os
import pathlib
import re
import sys
import time
import urllib.error
import urllib.request

_USER_AGENT = "Crubit-LLVM-Date/1.0"
_RETRYABLE_HTTP_CODES = frozenset({429, 500, 502, 503, 504})


def _fetch_url_with_retries(
    req: urllib.request.Request,
    retries: int = 3,
    initial_backoff: float = 1.0,
    timeout: float = 15.0,
) -> bytes:
  """Fetches a URL with exponential backoff on transient HTTP/network errors."""
  for attempt in range(retries + 1):
    try:
      with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read()
    except urllib.error.HTTPError as e:
      if e.code not in _RETRYABLE_HTTP_CODES or attempt == retries:
        raise
    except (urllib.error.URLError, TimeoutError):
      if attempt == retries:
        raise
    time.sleep(initial_backoff * (2**attempt))
  raise RuntimeError("Unreachable")


def _archive_root(src_dir: pathlib.Path) -> pathlib.Path:
  """Returns the extracted archive behind `src_dir`, which may be an overlay."""
  return (src_dir / "llvm" / "CMakeLists.txt").resolve().parents[1]


def _get_recorded_date(raw_root: pathlib.Path) -> str | None:
  """Returns the dev date that the llvm_source_fetch rule recorded, if any."""
  if not (raw_root / "llvm" / "CMakeLists.txt").is_file():
    return None
  try:
    build_content = (raw_root / "BUILD.bazel").read_text(
        encoding="utf-8", errors="replace"
    )
  except OSError:
    return None
  match = re.search(r"CRUBIT_LLVM_DEV_DATE=(\d{8})\b", build_content)
  return match.group(1) if match else None


def _is_main_version(raw_root: pathlib.Path) -> bool:
  """Whether an extracted archive carries main's LLVM version, X.0.0git."""
  # Release branches move to X.1.0 at their first release candidate.
  for path in (
      raw_root / "cmake" / "Modules" / "LLVMVersion.cmake",
      raw_root / "llvm" / "CMakeLists.txt",
  ):
    try:
      content = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
      continue
    fields = dict(
        re.findall(
            r"set\(LLVM_VERSION_(MINOR|PATCH|SUFFIX)\s*([^)\s]*)\s*\)",
            content,
        )
    )
    if fields:
      return fields == {"MINOR": "0", "PATCH": "0", "SUFFIX": "git"}
  return False


def _get_commit_date_from_source_dir(raw_root: pathlib.Path) -> str | None:
  """Extracts the LLVM commit date (YYYYmmDD UTC) from an extracted LLVM archive.

  GitHub's `/archive/<commit>.tar.gz` tarballs are generated by `git archive`,
  which sets every entry's `mtime` to the commit's committer timestamp. Bazel's
  `repository_ctx.download_and_extract` preserves these `mtime` values on disk.

  Args:
    raw_root: Root of an extracted `llvm-project` archive.

  Returns:
    The commit date in YYYYmmDD UTC format, or None if `raw_root` is not an
    extracted LLVM source archive or its mtimes aren't the commit's.
  """
  try:
    llvm_cmake = raw_root / "llvm" / "CMakeLists.txt"
    clang_cmake = raw_root / "clang" / "CMakeLists.txt"
    if not (llvm_cmake.is_file() and clang_cmake.is_file()):
      return None

    if (raw_root / ".git").exists():
      return None

    llvm_mtime = int(llvm_cmake.stat().st_mtime)
    clang_mtime = int(clang_cmake.stat().st_mtime)
    if llvm_mtime <= 0 or llvm_mtime != clang_mtime:
      return None

    utc_dt = datetime.datetime.fromtimestamp(
        llvm_mtime, datetime.timezone.utc
    )
    return utc_dt.strftime("%Y%m%d")
  except OSError:
    return None


def _gitiles_log(revisions: str, oldest: bool = False) -> dict | None:
  """Returns the newest (or oldest) entry of `git log <revisions>`, if any."""
  # Gitiles reverses the log before limiting it, unlike `git log`.
  url = (
      f"https://llvm.googlesource.com/llvm-project/+log/{revisions}"
      f"?n=1&format=JSON{'&reverse=true' if oldest else ''}"
  )
  req = urllib.request.Request(url, headers={"User-Agent": _USER_AGENT})
  raw = _fetch_url_with_retries(req)
  # Gitiles prefixes JSON with a line that keeps browsers from running it.
  log = json.loads(raw.decode("utf-8").split("\n", 1)[1])["log"]
  return log[0] if log else None


def _get_fork_date_from_gitiles(ref: str) -> str:
  """Fetches the date (YYYYmmDD UTC) of `ref`'s merge base with main."""
  # Release branches take cherry-picks, never merges from main, so the parent of
  # their oldest commit off main is where they forked.
  off_main = _gitiles_log(f"refs/heads/main..{ref}", oldest=True)
  fork = off_main["parents"][0] if off_main else ref
  if not (fork_entry := _gitiles_log(fork)):
    raise LookupError(f"Gitiles has no log for {fork}")
  committed = fork_entry["committer"]["time"]
  utc_dt = datetime.datetime.strptime(
      committed, "%a %b %d %H:%M:%S %Y %z"
  ).astimezone(datetime.timezone.utc)
  return utc_dt.strftime("%Y%m%d")


def _get_fork_date_from_github(ref: str) -> str:
  """Fetches the date (YYYYmmDD UTC) of `ref`'s merge base with main."""
  # Only the first page lists changed files, which can run to megabytes, so
  # query page 2. Every page, even one past the end, carries the merge base.
  url = (
      "https://api.github.com/repos/llvm/llvm-project/compare/"
      f"main...{ref}?per_page=1&page=2"
  )
  headers = {
      "User-Agent": _USER_AGENT,
      "Accept": "application/vnd.github+json",
  }
  if token := os.environ.get("GITHUB_TOKEN"):
    headers["Authorization"] = f"Bearer {token}"

  req = urllib.request.Request(url, headers=headers)
  raw = _fetch_url_with_retries(req)
  payload = json.loads(raw.decode("utf-8", errors="replace"))
  date_str = payload["merge_base_commit"]["commit"]["committer"]["date"]
  utc_dt = datetime.datetime.fromisoformat(
      date_str.replace("Z", "+00:00")
  ).astimezone(datetime.timezone.utc)
  return utc_dt.strftime("%Y%m%d")


def _get_fork_date(ref: str) -> str:
  """Fetches `ref`'s fork date from main from Gitiles, or else GitHub."""
  try:
    return _get_fork_date_from_gitiles(ref)
  except (
      urllib.error.URLError,
      TimeoutError,
      ValueError,
      LookupError,
  ) as gitiles_err:
    try:
      return _get_fork_date_from_github(ref)
    except Exception as github_err:  # pylint: disable=broad-exception-caught
      print(
          f"Error querying Gitiles for the fork date of {ref}: {gitiles_err}; "
          f"GitHub fallback also failed: {github_err}",
          file=sys.stderr,
      )
      sys.exit(1)


def _get_commit_date_from_env(commit: str) -> str | None:
  """Returns CRUBIT_LLVM_DEV_DATE from the environment if set and applicable."""
  env_date = os.environ.get("CRUBIT_LLVM_DEV_DATE", "").strip()
  if not re.fullmatch(r"\d{8}", env_date):
    return None
  env_commit = os.environ.get("CRUBIT_LLVM_COMMIT", "").strip()
  if env_commit and commit != env_commit:
    return None
  return env_date


def get_commit_date(
    commit: str, src_dir: pathlib.Path | None = None
) -> str:
  """Returns the dev date from env, extracted archive, or remote API."""
  if dev_date := _get_commit_date_from_env(commit):
    return dev_date
  raw_root = _archive_root(src_dir or pathlib.Path.cwd())
  if dev_date := _get_recorded_date(raw_root):
    return dev_date
  # A release commit's own date, as preserved in mtime, will postdate the main
  # commit timestamp to which the dev date corresponds.
  if _is_main_version(raw_root):
    if dev_date := _get_commit_date_from_source_dir(raw_root):
      return dev_date
  # Release commits and archives whose dev date cannot be determined via mtime
  # query the repository for the appropriate timestamp.
  return _get_fork_date(commit)


def get_llvm_commit_from_module_bazel() -> str:
  """Extracts the LLVM commit from MODULE.bazel."""
  module_bazel_path = (
      pathlib.Path(__file__).resolve().parents[2] / "MODULE.bazel"
  )
  content = module_bazel_path.read_text(encoding="utf-8")
  match = re.search(
      r'llvm_ext\.configure\s*\(\s*commit\s*=\s*["\']([0-9a-fA-F]+)["\']',
      content,
  )
  if not match:
    print(
        "Error: Could not find llvm_ext.configure(commit = ...) in"
        f" {module_bazel_path}",
        file=sys.stderr,
    )
    sys.exit(1)
  return match.group(1)


def get_llvm_commit() -> str:
  """Returns the configured LLVM commit from CRUBIT_LLVM_COMMIT or MODULE.bazel."""
  if env_commit := os.environ.get("CRUBIT_LLVM_COMMIT"):
    return env_commit.strip()
  return get_llvm_commit_from_module_bazel()


def main():
  if len(sys.argv) == 2:
    commit = sys.argv[1].strip()
  elif len(sys.argv) == 1:
    commit = get_llvm_commit()
  else:
    print(f"Usage: {sys.argv[0]} [commit_hash]", file=sys.stderr)
    sys.exit(1)

  dev_date = get_commit_date(commit)
  print(dev_date)


if __name__ == "__main__":
  main()
