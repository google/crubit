"""Resolves an LLVM commit timestamp and outputs it in YYYYmmDD format (UTC)."""

import base64
import datetime
import json
import os
import pathlib
import re
import sys
import time
import urllib.error
import urllib.request

_USER_AGENT = "Crubit-LLVM-Date/1.0"
_RETRYABLE_HTTP_CODES = frozenset({429, 500, 502, 503, 504})


def _fetch_url_with_retries(
    req: urllib.request.Request,
    retries: int = 3,
    initial_backoff: float = 1.0,
    timeout: float = 15.0,
) -> bytes:
  """Fetches a URL with exponential backoff on transient HTTP/network errors."""
  for attempt in range(retries + 1):
    try:
      with urllib.request.urlopen(req, timeout=timeout) as resp:
        return resp.read()
    except urllib.error.HTTPError as e:
      if e.code not in _RETRYABLE_HTTP_CODES or attempt == retries:
        raise
    except (urllib.error.URLError, TimeoutError):
      if attempt == retries:
        raise
    time.sleep(initial_backoff * (2**attempt))
  raise RuntimeError("Unreachable")


def get_commit_date_from_source_dir(
    src_dir: pathlib.Path | None = None,
) -> str | None:
  """Extracts the LLVM commit date (YYYYmmDD UTC) from an extracted LLVM archive.

  GitHub's `/archive/<commit>.tar.gz` tarballs are generated by `git archive`,
  which sets every entry's `mtime` to the commit's committer timestamp. Bazel's
  `repository_ctx.download_and_extract` preserves these `mtime` values on disk.

  Args:
    src_dir: Root of an extracted `llvm-project` archive (or `@llvm-project`
      overlay directory). Defaults to the current working directory.

  Returns:
    The commit date in YYYYmmDD UTC format, or None if `src_dir` is not an
    extracted LLVM source archive.
  """
  if src_dir is None:
    src_dir = pathlib.Path.cwd()

  try:
    llvm_cmake = src_dir / "llvm" / "CMakeLists.txt"
    clang_cmake = src_dir / "clang" / "CMakeLists.txt"
    if not (llvm_cmake.is_file() and clang_cmake.is_file()):
      return None

    raw_root = llvm_cmake.resolve().parents[1]
    if (src_dir / ".git").exists() or (raw_root / ".git").exists():
      return None

    # If @llvm-raw/BUILD.bazel was already generated by _llvm_source_fetch_impl,
    # reuse the CRUBIT_LLVM_DEV_DATE recorded there.
    raw_build = raw_root / "BUILD.bazel"
    if raw_build.is_file():
      build_content = raw_build.read_text(encoding="utf-8", errors="replace")
      match = re.search(r"CRUBIT_LLVM_DEV_DATE=(\d{8})\b", build_content)
      if match:
        return match.group(1)

    llvm_mtime = int(llvm_cmake.stat().st_mtime)
    clang_mtime = int(clang_cmake.stat().st_mtime)
    if llvm_mtime <= 0 or llvm_mtime != clang_mtime:
      return None

    utc_dt = datetime.datetime.fromtimestamp(
        llvm_mtime, datetime.timezone.utc
    )
    return utc_dt.strftime("%Y%m%d")
  except OSError:
    return None


def get_commit_date_from_github(commit: str) -> str:
  """Fetches the commit date from the GitHub REST API and returns YYYYmmDD in UTC."""
  url = f"https://api.github.com/repos/llvm/llvm-project/commits/{commit}"
  headers = {
      "User-Agent": _USER_AGENT,
      "Accept": "application/vnd.github+json",
  }
  if token := os.environ.get("GITHUB_TOKEN"):
    headers["Authorization"] = f"Bearer {token}"

  req = urllib.request.Request(url, headers=headers)
  raw = _fetch_url_with_retries(req)
  payload = json.loads(raw.decode("utf-8", errors="replace"))
  date_str = payload["commit"]["committer"]["date"]
  utc_dt = datetime.datetime.fromisoformat(
      date_str.replace("Z", "+00:00")
  ).astimezone(datetime.timezone.utc)
  return utc_dt.strftime("%Y%m%d")


def get_commit_date_from_gitiles(commit: str) -> str:
  """Fetches the commit date from Gitiles (with GitHub fallback) in YYYYmmDD UTC."""
  url = f"https://llvm.googlesource.com/llvm-project/+/{commit}?format=TEXT"
  req = urllib.request.Request(url, headers={"User-Agent": _USER_AGENT})
  try:
    raw = _fetch_url_with_retries(req)
    data = base64.b64decode(raw).decode("utf-8", errors="replace")
    match = re.search(r"^committer .*? (\d+) [+-]\d+", data, re.MULTILINE)
    if not match:
      raise ValueError(
          f"Could not parse committer line from Gitiles response for {commit}"
      )
    timestamp = int(match.group(1))
    utc_dt = datetime.datetime.fromtimestamp(timestamp, datetime.timezone.utc)
    return utc_dt.strftime("%Y%m%d")
  except (urllib.error.URLError, TimeoutError, ValueError) as gitiles_err:
    try:
      return get_commit_date_from_github(commit)
    except Exception as github_err:  # pylint: disable=broad-exception-caught
      print(
          f"Error querying Gitiles for commit {commit}: {gitiles_err}; "
          f"GitHub fallback also failed: {github_err}",
          file=sys.stderr,
      )
      sys.exit(1)


def get_commit_date_from_env(commit: str | None = None) -> str | None:
  """Returns CRUBIT_LLVM_DEV_DATE from the environment if set and applicable."""
  env_date = os.environ.get("CRUBIT_LLVM_DEV_DATE", "").strip()
  if not re.fullmatch(r"\d{8}", env_date):
    return None
  env_commit = os.environ.get("CRUBIT_LLVM_COMMIT", "").strip()
  if commit and env_commit and commit != env_commit:
    return None
  return env_date


def get_commit_date(
    commit: str, src_dir: pathlib.Path | None = None
) -> str:
  """Returns the commit date from env, extracted archive, or remote API."""
  if dev_date := get_commit_date_from_env(commit):
    return dev_date
  if dev_date := get_commit_date_from_source_dir(src_dir):
    return dev_date
  return get_commit_date_from_gitiles(commit)


def get_llvm_commit_from_module_bazel() -> str:
  """Extracts the LLVM commit from MODULE.bazel."""
  module_bazel_path = (
      pathlib.Path(__file__).resolve().parents[2] / "MODULE.bazel"
  )
  content = module_bazel_path.read_text(encoding="utf-8")
  match = re.search(
      r'llvm_ext\.configure\s*\(\s*commit\s*=\s*["\']([0-9a-fA-F]+)["\']',
      content,
  )
  if not match:
    print(
        "Error: Could not find llvm_ext.configure(commit = ...) in"
        f" {module_bazel_path}",
        file=sys.stderr,
    )
    sys.exit(1)
  return match.group(1)


def get_llvm_commit() -> str:
  """Returns the configured LLVM commit from CRUBIT_LLVM_COMMIT or MODULE.bazel."""
  if env_commit := os.environ.get("CRUBIT_LLVM_COMMIT"):
    return env_commit.strip()
  return get_llvm_commit_from_module_bazel()


def main():
  if len(sys.argv) == 2:
    commit = sys.argv[1].strip()
  elif len(sys.argv) == 1:
    commit = get_llvm_commit()
  else:
    print(f"Usage: {sys.argv[0]} [commit_hash]", file=sys.stderr)
    sys.exit(1)

  dev_date = get_commit_date(commit)
  print(dev_date)


if __name__ == "__main__":
  main()
